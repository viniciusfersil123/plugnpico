#!/usr/bin/env python3
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
COMPONENTS_JSON = ROOT / "components.json"
OUTPUT_HEADER = ROOT / "components_runtime.h"


def load_components(path: Path) -> dict:
    if not path.exists():
        return {}

    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)

    comps = data.get("components", {})
    if isinstance(comps, dict):
        return comps
    return {}


def collect_analog_controls(components: dict) -> list[tuple[str, int, int]]:
    """
    Returns list of tuples: (name, pin, adc_input)
    """
    analog = []
    for name, spec in components.items():
        if not isinstance(name, str):
            continue

        key_name = name.strip()
        if key_name == "":
            continue

        if not isinstance(spec, dict):
            continue

        kind = str(spec.get("component", "")).strip().lower()
        if kind != "analogcontrol":
            continue

        pin = spec.get("pin")
        if not isinstance(pin, int):
            continue

        # RP2040 ADC GPIOs are 26..29 -> ADC inputs 0..3
        if 26 <= pin <= 29:
            analog.append((key_name, pin, pin - 26))

    return analog


def generate_header(analog_controls: list[tuple[str, int, int]]) -> str:
    count = len(analog_controls)
    pins = ", ".join(str(pin) for _, pin, _ in analog_controls)
    inputs = ", ".join(str(adc_input) for _, _, adc_input in analog_controls)
    primary_receiver = analog_controls[0][0] if count > 0 else ""

    lines = [
        "// Auto-generated by generate_components.py. Do not edit manually.",
        "#ifndef COMPONENTS_RUNTIME_H",
        "#define COMPONENTS_RUNTIME_H",
        "",
        "#include <stdint.h>",
        "#include \"pico/types.h\"",
        "",
        f"#define ANALOG_CONTROL_COUNT {count}u",
        f"#define ANALOG_CONTROL_PRIMARY_RECEIVER \"{primary_receiver}\"",
        "",
    ]

    if count > 0:
        lines += [
            f"static const uint8_t analog_control_pins[ANALOG_CONTROL_COUNT] = {{{pins}}};",
            f"static const uint8_t analog_control_inputs[ANALOG_CONTROL_COUNT] = {{{inputs}}};",
        ]
    else:
        lines += [
            "static const uint8_t analog_control_pins[1] = {0};",
            "static const uint8_t analog_control_inputs[1] = {0};",
        ]

    lines += [
        "",
        "#endif",
        "",
    ]

    return "\n".join(lines)


def main() -> None:
    components = load_components(COMPONENTS_JSON)
    analog_controls = collect_analog_controls(components)
    content = generate_header(analog_controls)
    OUTPUT_HEADER.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
